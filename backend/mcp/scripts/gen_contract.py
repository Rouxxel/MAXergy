"""Generate src/maxergy_mcp/contract.py from the backend's Pydantic schemas.

The backend (`backend/src/models/forecast_schemas.py`) is the single source of truth for the
API contract. This script exports the JSON Schema of the models the MCP needs
(`HouseholdAssessment` as tool input, `PlanResponse` as the API response) and turns it into
Pydantic models with datamodel-code-generator, so the MCP never hand-copies the schema.

Usage (from backend/mcp):
    uv run python scripts/gen_contract.py          # regenerate
    uv run python scripts/gen_contract.py --check  # exit 1 if contract.py is out of date
"""

from __future__ import annotations

import importlib.util
import json
import sys
import tempfile
from pathlib import Path

from datamodel_code_generator import DataModelType, InputFileType, PythonVersion, generate
from datamodel_code_generator.format import Formatter
from pydantic.json_schema import models_json_schema

MCP_DIR = Path(__file__).resolve().parents[1]
SCHEMAS_FILE = MCP_DIR.parent / "src" / "models" / "forecast_schemas.py"
CONTRACT_FILE = MCP_DIR / "src" / "maxergy_mcp" / "contract.py"

HEADER = (
    "# GENERATED by backend/mcp/scripts/gen_contract.py from backend/src/models/forecast_schemas.py.\n"
    "# Do not edit by hand — change the backend schema and regenerate."
)


def _load_backend_schemas():
    spec = importlib.util.spec_from_file_location("maxergy_forecast_schemas", SCHEMAS_FILE)
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def _json_schema() -> str:
    s = _load_backend_schemas()
    _, schema = models_json_schema(
        [(s.HouseholdAssessment, "validation"), (s.PlanResponse, "serialization")],
        title="MAXergyContract",
    )
    return json.dumps(schema, indent=2, sort_keys=True)


def _render(output: Path) -> None:
    generate(
        _json_schema(),
        input_file_type=InputFileType.JsonSchema,
        output=output,
        output_model_type=DataModelType.PydanticV2BaseModel,
        custom_file_header=HEADER,
        disable_timestamp=True,
        use_standard_collections=True,
        use_union_operator=True,
        use_schema_description=True,
        field_constraints=True,
        use_annotated=True,
        target_python_version=PythonVersion.PY_311,
        formatters=[Formatter.BUILTIN],
    )


def main() -> int:
    check = "--check" in sys.argv
    if not check:
        _render(CONTRACT_FILE)
        print(f"wrote {CONTRACT_FILE}")
        return 0
    with tempfile.TemporaryDirectory() as d:
        fresh = Path(d) / "contract.py"
        _render(fresh)
        if fresh.read_text(encoding="utf-8") != CONTRACT_FILE.read_text(encoding="utf-8"):
            print("contract.py is out of date — run: uv run python scripts/gen_contract.py")
            return 1
    print("contract.py is up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
